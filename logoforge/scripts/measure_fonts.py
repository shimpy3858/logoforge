"""Measures real average glyph advance (em) per font and writes lib/fontMetrics.ts. Run after build-fonts."""
import json, glob, os
from fontTools.ttLib import TTFont
specs = json.load(open("scripts/font-specs.json"))
MIX = "Chai Corner Urban Bakery Nova Labs Green Leaf Studio Pixel Forge Blue Orbit Happy Fresh Market"
UP = "CHAI CORNER URBAN BAKERY NOVA LABS GREEN LEAF STUDIO PIXEL FORGE BLUE ORBIT"
DEV = "चाय कॉर्नर नमस्ते भारत दुनिया स्वागत बाज़ार किताब घर"
def adv(font, text):
    cmap = font.getBestCmap(); hm = font["hmtx"]; upm = font["head"].unitsPerEm
    tot = n = 0
    for ch in text:
        g = cmap.get(ord(ch))
        if g is None: continue
        tot += hm[g][0] / upm; n += 1
    return tot / max(n, 1)
out = {}
for s in specs:
    f = TTFont(f"public/fonts/{s['id']}-latin.woff2")
    w = 0.5 * adv(f, MIX) + 0.5 * adv(f, UP)
    row = {"wide": round(w * 1.04, 3)}
    if s["dev"]:
        d = TTFont(f"public/fonts/{s['id']}-devanagari.woff2")
        row["wideDev"] = round(adv(d, DEV) * 1.05, 3)
    out[s["id"]] = row
ts = "// generated by scripts/measure_fonts.py - real glyph widths (em per character)\nexport const METRICS: Record<string, { wide: number; wideDev?: number }> = " + json.dumps(out, indent=1) + ";\n"
open("lib/fontMetrics.ts", "w").write(ts)
print(json.dumps(out))
