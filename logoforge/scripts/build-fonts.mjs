// Copies the chosen woff2 files from node_modules/@fontsource into public/fonts and writes app/fonts.css.
// Run: npm run fonts   (only needed when you change scripts/font-specs.json; the output is committed)
import fs from "node:fs";
import path from "node:path";
const specs = JSON.parse(fs.readFileSync("scripts/font-specs.json", "utf8"));
fs.mkdirSync("public/fonts", { recursive: true });
let css = "/* generated by scripts/build-fonts.mjs - do not edit */\n";
const RANGE = {
  latin: "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+2074,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD",
  devanagari: "U+0900-097F,U+1CD0-1CF9,U+200C-200D,U+20A8,U+20B9,U+25CC,U+A830-A839,U+A8E0-A8FF",
};
for (const s of specs) {
  for (const sc of ["latin", ...(s.dev ? ["devanagari"] : [])]) {
    const src = `node_modules/@fontsource/${s.pkg}/files/${s.pkg}-${sc}-${s.w}-normal.woff2`;
    if (!fs.existsSync(src)) throw new Error("missing " + src);
    fs.copyFileSync(src, path.join("public/fonts", `${s.id}-${sc}.woff2`));
    // one file serves every weight (100-900) so the browser never fakes a bold
    css += `@font-face{font-family:'LF ${s.label}';font-style:normal;font-weight:100 900;font-display:swap;src:url(/fonts/${s.id}-${sc}.woff2) format('woff2');unicode-range:${RANGE[sc]}}\n`;
  }
}
fs.writeFileSync("app/fonts.css", css);
console.log("fonts:", specs.length);
